import { GroceryItem, GroceryProvider, PrepareShoppingMeta, PrepareShoppingResult } from './types.js';

const CATEGORY_KEYWORDS: Record<string, string[]> = {
  'Produce': [
    'onion', 'tomato', 'potato', 'garlic', 'ginger', 'chilli', 'chili', 'lemon', 'lime',
    'coriander', 'cilantro', 'mint', 'spinach', 'palak', 'methi', 'carrot', 'capsicum',
    'bell pepper', 'cauliflower', 'cabbage', 'peas', 'mushroom', 'cucumber', 'beans'
  ],
  'Dairy & Protein': [
    'paneer', 'milk', 'curd', 'yogurt', 'dahi', 'butter', 'ghee', 'cream', 'cheese',
    'chicken', 'mutton', 'fish', 'egg', 'tofu', 'soya'
  ],
  'Spices & Seasonings': [
    'turmeric', 'haldi', 'chilli powder', 'mirch', 'garam masala', 'cumin', 'jeera',
    'coriander powder', 'dhania', 'mustard seeds', 'rai', 'sarson', 'cardamom', 'elaichi',
    'clove', 'laung', 'cinnamon', 'dalchini', 'bay leaf', 'tejpatta', 'asafoetida', 'hing',
    'salt', 'black pepper', 'kasuri methi', 'chaat masala', 'kasoori'
  ],
  'Pantry & Staples': [
    'rice', 'flour', 'atta', 'maida', 'besan', 'sooji', 'rava', 'oil', 'mustard oil',
    'refined oil', 'olive oil', 'dal', 'lentil', 'sugar', 'jaggery', 'gur', 'pasta', 'noodle'
  ]
};

export function inferCategory(name: string, explicitCategory?: string): string {
  if (explicitCategory && explicitCategory.trim().length > 0) {
    return explicitCategory;
  }
  const lower = name.toLowerCase();
  
  let bestMatch: { category: string; length: number } | null = null;
  for (const [cat, keywords] of Object.entries(CATEGORY_KEYWORDS)) {
    for (const k of keywords) {
      if (lower.includes(k)) {
        if (!bestMatch || k.length > bestMatch.length) {
          bestMatch = { category: cat, length: k.length };
        }
      }
    }
  }

  return bestMatch ? bestMatch.category : 'Other';
}

export class CopyListGroceryProvider implements GroceryProvider {
  id = 'copy_list';
  name = 'Smart Grocery List';

  isAvailable(): boolean {
    return true;
  }

  async prepare(items: GroceryItem[], meta?: PrepareShoppingMeta): Promise<PrepareShoppingResult> {
    const title = meta?.recipeTitle ? `🛒 AajKyaBanaye — Shopping List for ${meta.recipeTitle}` : '🛒 AajKyaBanaye — Shopping List';
    const servingsText = meta?.servings ? ` (${meta.servings} servings)` : '';

    // Group items by category
    const grouped: Record<string, GroceryItem[]> = {};

    for (const item of items) {
      const category = inferCategory(item.groceryTerm || item.name, item.category);
      if (!grouped[category]) {
        grouped[category] = [];
      }
      grouped[category].push(item);
    }

    const lines: string[] = [`${title}${servingsText}`, ''];

    const categoryOrder = ['Produce', 'Dairy & Protein', 'Pantry & Staples', 'Spices & Seasonings', 'Other'];
    const allCategories = Array.from(new Set([...categoryOrder, ...Object.keys(grouped)]));

    for (const cat of allCategories) {
      const catItems = grouped[cat];
      if (!catItems || catItems.length === 0) continue;

      lines.push(`📦 ${cat.toUpperCase()}:`);
      for (const item of catItems) {
        const displayName = item.groceryTerm || item.name;
        const qty = item.quantity !== undefined && item.quantity > 0 ? `${item.quantity}` : '';
        const unit = item.unit && item.unit !== 'to_taste' && item.unit !== 'pcs' ? ` ${item.unit}` : (item.unit === 'pcs' ? ' pcs' : '');
        const amountStr = qty ? ` (${qty}${unit})` : (item.unit === 'to_taste' ? ' (to taste)' : '');
        const noteStr = item.note ? ` — ${item.note}` : '';
        lines.push(`  • ${displayName}${amountStr}${noteStr}`);
      }
      lines.push('');
    }

    lines.push('✨ Generated by AajKyaBanaye — Happy Cooking!');

    const formattedText = lines.join('\n').trim();

    return {
      provider: this.id,
      type: 'copied',
      text: formattedText,
      itemCount: items.length,
      message: 'Categorized shopping list generated successfully.'
    };
  }
}
